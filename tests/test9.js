const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:1280,height:900}}); const pg=await ctx.newPage();
 const errs=[]; pg.on('pageerror',e=>errs.push(e.message)); pg.on('console',m=>{ if(m.type()==='error') errs.push(m.text()); });
 const html=fs.readFileSync('radar.html','utf8');
 fs.writeFileSync('local.html','<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><script>window.__RADAR_DEMO_MS=8000</script>'+html+'</body></html>');
 await pg.goto('file://'+process.cwd()+'/local.html#grafico'); await pg.waitForTimeout(3000);
 const hint=async()=>pg.evaluate(()=>[0,1].map(i=>document.getElementById('ch'+i).textContent));
 console.log('init', await hint());
 const box=await pg.locator('#cv0').boundingBox();
 await pg.mouse.move(box.x+box.width/2, box.y+box.height/2);
 await pg.mouse.wheel(0,300); await pg.waitForTimeout(200); await pg.mouse.wheel(0,300); await pg.waitForTimeout(300);
 console.log('zoom out', await hint());
 await pg.mouse.down(); await pg.mouse.move(box.x+box.width/2+250, box.y+box.height/2,{steps:8}); await pg.mouse.up(); await pg.waitForTimeout(300);
 console.log('drag back', await hint());
 await pg.click('#cp1 [data-z="in"]'); await pg.click('#cp1 [data-z="in"]'); await pg.click('#cp1 [data-z="left"]'); await pg.waitForTimeout(300);
 console.log('btns chart2', await hint());
 await pg.screenshot({path:'d-graficos.png', fullPage:true});
 await pg.waitForTimeout(9000); console.log('after new candle', await hint());
 await pg.dblclick('#cv0'); await pg.waitForTimeout(300); console.log('reset', await hint());
 await pg.click('#pc1 button:nth-child(2)'); await pg.waitForTimeout(1200); console.log('titles', await pg.evaluate(()=>[0,1].map(i=>document.getElementById('ct'+i).textContent)));
 await pg.setViewportSize({width:375,height:812}); await pg.waitForTimeout(800);
 console.log('scrollW',await pg.evaluate(()=>document.documentElement.scrollWidth));
 await pg.screenshot({path:'m-graficos.png'});
 await pg.click('#btnCfg').catch(()=>{});
 console.log('errs',errs.slice(0,8));
 await b.close();
})();
